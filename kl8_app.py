# -------------------------- 你原版：双流派分析 --------------------------
def dual_style_analysis(df, recent=20):
    recent_data = df.tail(recent)["所有号码"].tolist()
    all_nums = []
    for nums in recent_data:
        all_nums.extend(nums)
    
    count = collections.Counter(all_nums)
    top24 = sorted(count.items(), key=lambda x: x[1], reverse=True)[:24]
    bottom24 = sorted(count.items(), key=lambda x: x[1])[:24]
    
    热号池 = [k for k, v in top24]
    冷号池 = [k for k, v in bottom24]
    
    return 热号池, 冷号池, count

# -------------------------- 你原版：相随号统计 --------------------------
def get_xiang_sui(df):
    sui_pairs = collections.defaultdict(int)
    for nums in df["所有号码"]:
        s = sorted(nums)
        for i in range(len(s)-1):
            a, b = s[i], s[i+1]
            if b - a == 1:
                sui_pairs[(a, b)] += 1
    top_sui = sorted(sui_pairs.items(), key=lambda x: x[1], reverse=True)[:20]
    return top_sui

# -------------------------- 你原版：相随号 → 对应跟随号 --------------------------
def get_sui_follow(df):
    sui = get_xiang_sui(df)
    top_pairs = [p[0] for p in sui[:10]]
    follow_map = collections.defaultdict(list)
    data = df["所有号码"].tolist()
    
    for i in range(len(data)-1):
        current = data[i]
        next_nums = data[i+1]
        for (a, b) in top_pairs:
            if a in current and b in current:
                follow_map[(a, b)].extend(next_nums)
    
    result = {}
    for pair, nums in follow_map.items():
        result[pair] = collections.Counter(nums).most_common(5)
    return result

